"""
Исключения движка графа.

GraphError            — базовое.
GraphValidationError  — граф некорректен (неизвестный узел, висячий провод,
                        несовместимые типы, цикл, незаполненный обязательный вход).
                        Бросается при сборке/загрузке, до исполнения.
RetryGeneration       — узел сообщает: текущая попытка непригодна, нужно
                        пере-сгенерировать граф целиком (новые случайные значения).
                        Используется узлом constraint и формулой при числовой
                        ошибке — это аналог `continue` в fisic_generater.generate_task.
"""

from __future__ import annotations


class GraphError(Exception):
    """Базовая ошибка движка графа."""


class GraphValidationError(GraphError):
    """Граф структурно некорректен (обнаруживается до исполнения)."""


class RetryGeneration(GraphError):
    """Сигнал: пере-сгенерировать весь граф (whole-graph retry)."""


def internal_error_text(exc: BaseException) -> str:
    """
    Текст НЕПРЕДВИДЕННОГО исключения (не GraphError) для показа автору графа.

    core/graph/worker.py и core/graph/isolation.py ловят исключения, которые
    движок не ожидал (баг узла/пакета, а не GraphValidationError/
    RetryGeneration) — их родное сообщение `{type(exc).__name__}: {exc}` по
    построению английское: имя класса Python и текст из stdlib/sympy/PIL.
    Отдать его как есть значило бы показать автору графа внутренности
    рантайма.

    Убирать техническую часть нельзя — `type(exc).__name__` и текст exc
    нужны для диагностики и обращений в поддержку (та же причина, по которой
    node_ref() в node.py не выбрасывает type_id, а сдвигает его вторым).
    Поэтому она остаётся, но ПОСЛЕ понятной русской фразы — тот же принцип
    разделения «сообщение человеку» / «подробности», что и в конверте
    ошибок сервиса (generator_service/errors.py: envelope() отдаёт message
    отдельно от технических деталей). Там это два разных поля JSON; здесь
    протокол worker.py — плоская строка `error`, поэтому подробности идут
    после явного разделителя в той же строке, а не отдельным полем.
    """
    return (f"Внутренняя ошибка исполнения графа. "
            f"Подробности: {type(exc).__name__}: {exc}")
