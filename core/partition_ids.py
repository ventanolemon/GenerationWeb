"""
Номер раздела: единственное, что связывает запись в БД с обслуживающим её
кодом. Здесь он выдаётся — и только здесь.

Замер, из-за которого модуль появился
-------------------------------------
Английские словари получали номер по МЕСТУ файла в отсортированном списке:
`pid = 1000 + i`. На двух машинах списки разной длины, и одно и то же
число означает разные словари:

    id     сервер (20 файлов)          десктоп (12 файлов)
    1000   complete_abbreveations      complete_abbreveations
    1001   complete_vocabulary         complete_words          ← разошлись
    1002   complete_words              term_4_complete_vocabulary
    …

Синхронизация переносит разделы ПО НОМЕРУ. Значит, домашнее задание,
выданное на сервере по разделу 1001, открывает на десктопе другой словарь —
молча, без единой ошибки. То же самое происходит во времени на одной
машине: добавили файл в начало алфавита — и все последующие словари
переехали, а выданные задания остались указывать на старые номера.

Следствия того же дефекта, найденные тем же прогоном: в поставочной БД
десктопа лежат пять разделов `Английский: unit1_history…unit5_secondary_storage`
с `constracted = 0`, которым не соответствует ни один генератор (файлы
давно переименованы), и раздел «конструктор» предмета Физика с тем же
`constracted = 0`, для которого кода не было никогда.

Правило
-------
**Номер раздела выводится из ИМЕНИ, а не из положения.** Имя файла — это
то, что автор задумал; порядок в каталоге — случайность окружения. Поэтому

    pid = БАЗА_ПОЛОСЫ + crc32(имя) % ШИРИНА_ПОЛОСЫ

`crc32` взят не за криптостойкость, а за воспроизводимость: `hash()` в
Python рандомизируется от запуска к запуску, и номер раздела, посчитанный
через него, разъезжался бы даже на одной машине.

Столкновение двух имён в полосе шириной в миллион при десятках файлов —
событие, которого на практике не происходит; но если оно произойдёт, оно
обязано быть ГРОМКИМ (`PartitionIdCollision`), а не разрешаться подбором
свободного места: подбор вернул бы зависимость от того, какие ещё файлы
лежат рядом, то есть ровно тот дефект, ради устранения которого модуль и
написан.

Полосы
------
Полоса — это обещание: «номера отсюда выдаёт код, база их не занимает».
Динамические разделы (то, что заводит пользователь) полосы обходят —
см. `next_dynamic_id`.
"""

from __future__ import annotations

import zlib
from typing import Iterable


class PartitionIdCollision(RuntimeError):
    """Два разных имени претендуют на один номер раздела."""


#: Ручные номера код-генераторов (линал, матан, ОПВС) — заданы в bootstrap
#: поимённо. Полосой не управляем: их немного и они историчны.
CODE_MAX = 999

#: Старая позиционная полоса английского. Только для ЧТЕНИЯ при переносе:
#: новые номера сюда не выдаются никогда.
LEGACY_ENGLISH = range(1000, 2000)

#: Разделы-графы из поставки (`exercises/model_tasks`).
MODEL_TASKS = range(9000, 10000)

#: Словарный тренажёр английского.
ENGLISH_WORDS = range(1_000_000, 2_000_000)

#: Multiple-choice по транскрипции — параллельный раздел к тому же словарю.
ENGLISH_TRANSCRIPTION = range(2_000_000, 3_000_000)

#: Произношение вслух — третий раздел того же словаря.
#:
#: Полоса объявлена ОБЕИМИ сторонами, хотя разделы в ней заводит пока
#: только десктоп: захват звука есть у него. Иначе `next_dynamic_id` на
#: сервере выдал бы пользовательскому разделу номер, который на десктопе
#: занят кодом, — то есть ровно тот дефект расхождения установок, ради
#: которого модуль написан. Полоса — это обещание «сюда не селиться», и
#: обещание должно быть общим раньше, чем появится первый жилец.
ENGLISH_PRONUNCIATION = range(3_000_000, 4_000_000)

#: Всё, что выдаёт код. Динамическая выдача обязана это обходить.
RESERVED: tuple[range, ...] = (
    MODEL_TASKS, ENGLISH_WORDS, ENGLISH_TRANSCRIPTION, ENGLISH_PRONUNCIATION,
)


def is_reserved(partition_id: int) -> bool:
    """Занят ли номер полосой, которой распоряжается код."""
    return any(partition_id in band for band in RESERVED)


def stable_id(name: str, band: range) -> int:
    """
    Номер раздела для имени `name` внутри полосы `band`.

    Зависит ТОЛЬКО от имени: одно и то же имя даёт одно и то же число на
    любой машине, в любом порядке файлов, в любом запуске Python.
    """
    key = name.strip().lower().encode("utf-8")
    return band.start + zlib.crc32(key) % len(band)


def english_words_id(stem: str) -> int:
    """Номер раздела словарного тренажёра для файла `<stem>.json`."""
    return stable_id(stem, ENGLISH_WORDS)


def english_transcription_id(stem: str) -> int:
    """Номер раздела «выбери транскрипцию» для того же файла."""
    return stable_id(stem, ENGLISH_TRANSCRIPTION)


def english_pronunciation_id(stem: str) -> int:
    """Номер раздела «произнесите вслух» для того же файла."""
    return stable_id(stem, ENGLISH_PRONUNCIATION)


def assign(names: Iterable[str], band: range) -> dict[str, int]:
    """
    Разложить имена по полосе, проверив, что столкновений нет.

    Возвращает `имя → номер`. При столкновении бросает — молчаливое
    разрешение вернуло бы зависимость номера от соседей по каталогу.
    """
    out: dict[str, int] = {}
    used: dict[int, str] = {}
    for name in names:
        pid = stable_id(name, band)
        if pid in used and used[pid] != name:
            raise PartitionIdCollision(
                f"Имена {used[pid]!r} и {name!r} дают один номер раздела "
                f"{pid}. Переименуйте один из файлов — номер выводится из "
                f"имени и подбирать свободное место нельзя."
            )
        used[pid] = name
        out[name] = pid
    return out


def next_dynamic_id(existing: Iterable[int]) -> int:
    """
    Следующий номер для раздела, который заводит ПОЛЬЗОВАТЕЛЬ.

    Берётся за наибольшим из уже занятых динамических номеров и
    перепрыгивает полосы кода. Без прыжка автоинкремент SQLite рано или
    поздно дорастает до полосы и начинает раздавать занятые номера —
    именно так разделы «Группа» и «Группа_2» получили 1017 и 1018,
    вплотную к словарям английского.
    """
    dynamic = [pid for pid in existing if not is_reserved(pid)]
    candidate = (max(dynamic) + 1) if dynamic else 1
    while is_reserved(candidate):
        # За конец полосы, а не +1: иначе следующий шаг снова внутри.
        for band in RESERVED:
            if candidate in band:
                candidate = band.stop
    return candidate
