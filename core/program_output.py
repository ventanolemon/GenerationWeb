"""
Что считать одинаковым выводом программы.

Второй случай того же устройства, что и `boolean_text`: определение
равенства нужно двум сторонам сразу — модели (`Instance.equivalent`) и
проверке ответа (`OutputSpec`), — и жить оно обязано в одном месте. Две
реализации разошлись бы молча: студенту засчитали бы то, что модель
считает другим ответом.

Правило простое и вытекает из того, чем ответ набирают. Хвостовые пробелы
и лишние переводы строки в конце — след клавиатуры, а не ответ. Состав
строк и их порядок — ответ: «выполните программу на бумаге» ровно об этом,
и три величины на трёх строках не то же самое, что те же три в одну строку
или в другом порядке.
"""

from __future__ import annotations

from typing import List


def output_rows(value) -> List[str]:
    """Строки вывода без хвостовых пробелов и пустого хвоста."""
    return [line.rstrip() for line in str(value).rstrip().split("\n")]


def same_output(expected, answer) -> bool:
    """Один ли это вывод программы."""
    return output_rows(expected) == output_rows(answer)
