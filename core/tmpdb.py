"""
Временный файл БД для прогона — такой, что после себя ничего не оставляет.

Зачем отдельный помощник
------------------------
`tempfile.mktemp(suffix=".db")` даёт имя, а дальше тест сам решает, когда
файл убрать. Убирают обычно ОДИН файл — тот, имя которого получили. Но
SQLite рядом с базой держит хвосты журнала `-wal` и `-shm`, и они
переживают удаление самой базы: тест удаляет `.db`, пока соединение ещё
открыто, и подчистить хвосты на закрытии SQLite уже нечем.

Так и вышло: во временном каталоге накопилось 37 065 пар `-wal`/`-shm`
на 29 ГБ, диск встал на 100%, и очередной прогон дал 144 ошибки — не
потому, что код сломался, а потому, что тестам стало некуда писать.
Диагноз при этом выглядел как регрессия в коде: ошибки пришли сразу
после правки, к которой отношения не имели.

Что делает
----------
Файлы кладутся не в общий временный каталог, а в СВОЙ на прогон, и в
конце процесса он сносится целиком. «Целиком» здесь и есть содержание:
уходит не тот файл, который вспомнили, а всё, что рядом с ним завелось,
— хвосты журнала, чужие снимки, что угодно.

Модуль лежит в `core/` и зеркалится, как остальное ядро. Не потому, что
это понятие предметной области — это оснастка прогона, — а потому, что
дом у него обязан быть ОДИН: серверные тесты живут в `core/`, десктопные
в `tests/`, и часть файлов зеркалится между репозиториями. Помощник,
лежащий по разным адресам, сломал бы такой файл на той стороне, где его
не оказалось.

Применение:
    from core.tmpdb import temp_path

    path = temp_path()              # ещё не существующий путь к .db
    repo = Repository(path)
"""

from __future__ import annotations

import atexit
import os
import shutil
import tempfile
from pathlib import Path

_ROOT: Path | None = None


def root() -> Path:
    """Каталог прогона. Заводится при первом обращении, сносится в конце."""
    global _ROOT
    if _ROOT is None:
        _ROOT = Path(tempfile.mkdtemp(prefix="gen-tests-"))
        atexit.register(shutil.rmtree, _ROOT, True)
    return _ROOT


def temp_path(suffix: str = ".db") -> str:
    """
    Путь к ещё НЕ существующему файлу внутри каталога прогона.

    Не существует намеренно: вызывающий обычно либо копирует туда
    поставочную базу, либо отдаёт путь `Repository`, который заводит файл
    сам. Имя занимается через `mkstemp`, поэтому два параллельных
    обращения не столкнутся.
    """
    handle, path = tempfile.mkstemp(suffix=suffix, dir=root())
    os.close(handle)
    os.unlink(path)
    return path


def temp_dir(prefix: str = "case-") -> str:
    """Отдельный каталог внутри каталога прогона (для наборов файлов)."""
    return tempfile.mkdtemp(prefix=prefix, dir=root())
