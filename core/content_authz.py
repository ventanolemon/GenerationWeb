"""
Кто вправе трогать авторский контент — одно правило на все пути к нему.

## Зачем отдельный модуль

К одной и той же таблице ведут ДВА пути записи: push синхронизации
(`core/sync_api.py`) и CRUD по HTTP (`POST/DELETE /partitions`), — и два
пути чтения авторского содержимого: pull синхронизации и
`GET /partitions/{id}`. Правила «кому можно» у них обязаны быть общими, и
держать их в нескольких местах нельзя — не потому что это дублирование, а
потому что расхождение уже случалось дважды: синк проверял актора, роль и
владельца, а CRUD не проверял НИЧЕГО; pull ограничивал скоуп выдач, а
чтение через HTTP отдавало весь авторский граф по id кому угодно.

Дыра такого рода и заводится именно так: правило пишут там, где о нём
подумали, а второй вход добавляют позже и про правило не вспоминают.
Поэтому здесь оно одно, и оба входа зовут его, а не повторяют.

## Само правило, по убыванию строгости

1. **Правка контента требует идентичности.** Телеметрию (attempts,
   word_stats) аноним слать вправе — её и шлёт гость, решающий задачи; но
   менять общий каталог устройство без логина не может.
2. **Роль.** Контент правят `teacher` и `admin` (RBAC §3); `admin` — что
   угодно, и дальше не проверяется.
3. **Чужое — нельзя.** Предмет с владельцем, отличным от актора,
   преподавателю недоступен на запись, каким бы ни был набор выдач: выдача
   даёт ПРАВО ВИДЕТЬ, а не переписывать. У раздела собственных прав нет —
   они выводятся из предмета (одна точка истины, RBAC §3).

## Встроенные предметы остаются доступными преподавателю

`owner_user_id IS NULL` — общий каталог, и на запись он преподавателю
открыт. Это сознательное отступление от таблицы прав RBAC (там встроенные
— admin-only): сегодня это тот самый каталог, в который преподаватели
складывают свои разделы через `POST /partitions`, и запрет здесь развёл бы
два пути записи (веб — можно, синк — нельзя), сломав десктопу ровно тот
сценарий, ради которого он существует. Сужение до admin-only — отдельное
продуктовое решение, и делать его молча, попутно с закрытием дыры,
неправильно.

## Чтение — отдельное правило, не копия правила записи

`check_authoring_read` мягче по владельцу (выданный чужой предмет читать
можно — ровно для этого выдача и нужна, и синк такой граф уже присылает) и
строже по роли (`generation_params` — «кишки» задания, решающему они не
нужны). Общее у чтения и записи — скоуп: `visible_scope` живёт здесь же и
служит обоим.

## Форма ответа

Возвращается `(status, reason)` или `None`. Пара, а не исключение, потому
что вызывающие разные: синку нужна строка для конверта конфликта
(`forbidden: true`), роутеру — HTTP-статус. Кидать исключение и ловить его
в синке ради текста было бы хуже читаемо, чем вернуть данные.
"""

from __future__ import annotations

from typing import Iterable, Optional

from . import grants_api
from .repository import Repository

# Роли, которым вообще доступна запись контента (RBAC §3).
WRITE_ROLES = ("teacher", "admin")

# Отказ без идентичности — 401 (не «нельзя», а «неизвестно кто»), отказ по
# роли и по владельцу — 403 (известно кто, и ему нельзя). Разница не
# косметическая: по 401 клиент понимает, что надо войти, по 403 — что
# входить бесполезно.
UNAUTHENTICATED = 401
FORBIDDEN = 403
# Чужое при ЧТЕНИИ отвечает 404, а не 403: иначе перебором последовательных
# id выясняется, какие разделы существуют у коллег. Тот же принцип, что в
# публичном API — «нет такого» и «есть, но не для вас» обязаны отвечать
# одинаково. На записи так делать незачем: туда попадают, уже зная id.
NOT_FOUND = 404


def check_subject_write(
    repo: Repository, subject_ids: Iterable[int],
    actor: Optional[str], role: str,
) -> Optional[tuple[int, str]]:
    """
    Вправе ли актор писать в эти предметы. `None` — вправе; `(status,
    reason)` — отказ.

    `subject_ids` — набор, а не один id, потому что перенос раздела между
    предметами затрагивает ОБА: и тот, откуда уносим, и тот, куда кладём.
    Проверить только целевой значило бы разрешить вынос чужого раздела к
    себе.
    """
    if not actor:
        return (UNAUTHENTICATED,
                "Правка контента требует идентичности (X-User-Id): "
                "анонимное устройство не меняет общий каталог.")
    if role not in WRITE_ROLES:
        return (FORBIDDEN,
                f"Роль {role!r} не правит контент — только teacher и admin.")
    if role == "admin":
        return None

    for subject_id in sorted({int(s) for s in subject_ids}):
        owner = repo.subject_owner(subject_id)
        if owner is not None and owner != actor:
            return (FORBIDDEN,
                    f"Предмет #{subject_id} принадлежит другому владельцу; "
                    f"выдача даёт право видеть, а не править.")
    return None


def check_entity_change(
    repo: Repository, kind: str, row: Optional[dict], data: dict,
    actor: Optional[str], role: str,
) -> Optional[tuple[int, str]]:
    """
    То же правило в форме, удобной синку: сущность задана видом, текущей
    строкой (если есть) и приезжающими данными.

    Для раздела в набор попадают оба предмета — прежний (из строки) и
    новый (из данных): это и есть тот самый перенос, ради которого
    `check_subject_write` принимает набор.
    """
    subject_ids: set[int] = set()
    if kind == "subject":
        if row is not None:
            subject_ids.add(int(row["id"]))
    else:
        if row is not None:
            subject_ids.add(int(row["subject_id"]))
        if data.get("subject_id") is not None:
            subject_ids.add(int(data["subject_id"]))
    return check_subject_write(repo, subject_ids, actor, role)


# ---------- Область видимости (чтение) ----------

def visible_scope(
    repo: Repository, user_id: Optional[str], role: str,
) -> Optional[list[int]]:
    """
    subject_id, видимые пользователю; None = «видно всё» (dev-заглушка,
    когда web_layer ещё не пробросил identity). Реальный RBAC уже подключён:
    с identity область считает Repository.visible_subject_ids (админ — все,
    прочие — системные + свои). Область назначений студента (партиции его
    групп) подключится сюда же, когда появятся назначения.

    Поверх RBAC накладываются выдачи предметов (docs/subject_grants.md).
    Скоуп pull'а — это ровно тот механизм, которым документ withhold'ит
    АВТОРСКИЙ контент (встроенные предметы им не удержать: десктоп
    пересоздаёт их из своего кода на каждом старте, для них ограничение
    UI-уровневое и живёт в клиентском фильтре витрины). Поэтому выдача
    работает в обе стороны:

      * расширяет — выданный предмет приезжает преподавателю, даже если
        владелец другой (в этом и смысл «админ раздаёт доступ»; без этого
        серверная половина не удерживала бы ничего, кроме встроенных);
      * сужает — всё невыданное, включая встроенное, из скоупа уходит.

    Собственные предметы преподавателя остаются в скоупе при ЛЮБОМ наборе
    выдач. Это не косметика: клиент по завершении пересборки удаляет у себя
    всё, чего в присланном наборе не было, и выпади оттуда авторский контент
    преподавателя — отзыв доступа к чужому предмету стёр бы ему собственную
    работу. Витрину его же предметов при этом всё равно ограничивает
    клиентский фильтр, а он ничего не удаляет.
    """
    if user_id is None:
        return None
    visible = repo.visible_subject_ids(user_id, role)
    allowed = grants_api.granted_scope(repo, user_id, role)
    if allowed is None:
        return visible
    return sorted(_within_organization(
        repo, user_id, allowed | set(repo.owned_subject_ids(user_id))))


def _within_organization(repo: Repository, user_id: str,
                         subject_ids: set[int]) -> set[int]:
    """
    Выбросить из набора предметы чужих организаций (§8.1).

    Нужна отдельно от `visible_subject_ids`, потому что выдачи
    (`granted_scope`) считаются мимо неё — по таблице `subject_grants`. Через
    API выдать предмет преподавателю чужой организации нельзя, но полагаться
    на это одно значило бы держать границу контейнера на том, что её негде
    нарушить. Здесь она держится на том, что нарушение не проходит.

    Встроенные предметы (`organization_id IS NULL`) остаются: они
    принадлежат продукту и видны всем — единственное, что пересекает
    границу.
    """
    if repo.is_superuser(user_id):
        return subject_ids
    org_id = repo.user_organization_id(user_id)
    return {sid for sid in subject_ids
            if repo.subject_organization_id(sid) in (None, org_id)}


def check_authoring_read(
    repo: Repository, subject_ids: Iterable[int],
    actor: Optional[str], role: str,
) -> Optional[tuple[int, str]]:
    """
    Вправе ли актор ЧИТАТЬ авторское содержимое этих предметов —
    `generation_params` раздела, то есть сам граф или конфиг генератора.
    `None` — вправе; `(status, reason)` — отказ.

    Правило отличается от права на запись в обе стороны, и оба отличия
    осмысленны:

    * **мягче по владельцу.** Выданный предмет чужого владельца читать
      можно: выдача ровно для этого и нужна, и синк такому преподавателю
      этот граф уже присылает. Запрет здесь развёл бы веб и синк — то, из-за
      чего и появилась дыра на записи;
    * **строже по роли.** Нужен teacher/admin. `generation_params` — это
      «кишки» задания: формулы, диапазоны, устройство графа. Решающему они
      не нужны — веб-клиент ничего локально не генерирует, задание собирает
      сервер, — а знание внутренностей помогает угадывать ответы.

    Десктопу тот же граф приезжает синком и студенту тоже, и это не
    противоречие: десктоп генерирует ЛОКАЛЬНО, без параметров он попросту
    не работает офлайн. Разные клиенты, разные потребности; общее у них —
    скоуп, и он здесь тот же самый.

    **Отсутствие идентичности — отказ, а не «видно всё».** У `visible_scope`
    есть dev-заглушка на этот случай, но она годится для синка, куда
    десктоп ходит своим путём; здесь она была бы самой дырой.

    **Чужое отвечает 404, а не 403.** Иначе перебором последовательных id
    выясняется, какие разделы существуют у коллег. Тот же принцип, что в
    публичном API: «нет такой темы» и «тема есть, но не для вас» обязаны
    отвечать одинаково.
    """
    if not actor:
        return (UNAUTHENTICATED,
                "Чтение содержимого раздела требует идентичности "
                "(X-User-Id).")
    if role not in WRITE_ROLES:
        return (FORBIDDEN,
                f"Роль {role!r} не читает содержимое разделов — оно нужно "
                f"только для редактирования.")

    scope = visible_scope(repo, actor, role)
    if scope is None:
        return None
    allowed = set(scope)
    for subject_id in sorted({int(s) for s in subject_ids}):
        if subject_id not in allowed:
            return (NOT_FOUND, "Раздел не найден.")
    return None


def readable_subject_ids(repo: Repository, actor: Optional[str],
                         role: str) -> Optional[set[int]]:
    """
    Скоуп чтения набором — для мест, где надо не отказать, а ОТФИЛЬТРОВАТЬ.
    `None` — ограничивать нечем (без идентичности сюда просто не пускают).

    Нужно ровно для `/partitions/candidates`: он отдаёт разделы соседних
    предметов, и вернуть оттуда чужое значило бы обойти проверку с другой
    стороны — не «покажи мне чужой раздел», а «покажи мне список, в котором
    он окажется».
    """
    scope = visible_scope(repo, actor, role)
    return None if scope is None else set(scope)
