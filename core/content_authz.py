"""
Кто вправе править авторский контент — одно правило на все пути записи.

## Зачем отдельный модуль

К одной и той же таблице ведут ДВА пути записи: push синхронизации
(`core/sync_api.py`) и CRUD по HTTP (`POST/DELETE /partitions`). Правило
«кому можно» у них обязано быть одно, и держать его в двух местах нельзя —
не потому что это дублирование, а потому что расхождение уже случилось:
синк проверял актора, роль и владельца, а CRUD не проверял НИЧЕГО. Любой,
кто дотянулся до сервиса, мог переписать или снести чужой раздел, послав
запрос мимо синка.

Дыра такого рода и заводится именно так: правило пишут там, где о нём
подумали, а второй вход добавляют позже и про правило не вспоминают.
Поэтому здесь оно одно, и оба входа зовут его, а не повторяют.

## Само правило, по убыванию строгости

1. **Правка контента требует идентичности.** Телеметрию (attempts,
   word_stats) аноним слать вправе — её и шлёт гость, решающий задачи; но
   менять общий каталог устройство без логина не может.
2. **Роль.** Контент правят `teacher` и `admin` (RBAC §3); `admin` — что
   угодно, и дальше не проверяется.
3. **Чужое — нельзя.** Предмет с владельцем, отличным от актора,
   преподавателю недоступен на запись, каким бы ни был набор выдач: выдача
   даёт ПРАВО ВИДЕТЬ, а не переписывать. У раздела собственных прав нет —
   они выводятся из предмета (одна точка истины, RBAC §3).

## Встроенные предметы остаются доступными преподавателю

`owner_user_id IS NULL` — общий каталог, и на запись он преподавателю
открыт. Это сознательное отступление от таблицы прав RBAC (там встроенные
— admin-only): сегодня это тот самый каталог, в который преподаватели
складывают свои разделы через `POST /partitions`, и запрет здесь развёл бы
два пути записи (веб — можно, синк — нельзя), сломав десктопу ровно тот
сценарий, ради которого он существует. Сужение до admin-only — отдельное
продуктовое решение, и делать его молча, попутно с закрытием дыры,
неправильно.

## Форма ответа

Возвращается `(status, reason)` или `None`. Пара, а не исключение, потому
что вызывающие разные: синку нужна строка для конверта конфликта
(`forbidden: true`), роутеру — HTTP-статус. Кидать исключение и ловить его
в синке ради текста было бы хуже читаемо, чем вернуть данные.
"""

from __future__ import annotations

from typing import Iterable, Optional

from .repository import Repository

# Роли, которым вообще доступна запись контента (RBAC §3).
WRITE_ROLES = ("teacher", "admin")

# Отказ без идентичности — 401 (не «нельзя», а «неизвестно кто»), отказ по
# роли и по владельцу — 403 (известно кто, и ему нельзя). Разница не
# косметическая: по 401 клиент понимает, что надо войти, по 403 — что
# входить бесполезно.
UNAUTHENTICATED = 401
FORBIDDEN = 403


def check_subject_write(
    repo: Repository, subject_ids: Iterable[int],
    actor: Optional[str], role: str,
) -> Optional[tuple[int, str]]:
    """
    Вправе ли актор писать в эти предметы. `None` — вправе; `(status,
    reason)` — отказ.

    `subject_ids` — набор, а не один id, потому что перенос раздела между
    предметами затрагивает ОБА: и тот, откуда уносим, и тот, куда кладём.
    Проверить только целевой значило бы разрешить вынос чужого раздела к
    себе.
    """
    if not actor:
        return (UNAUTHENTICATED,
                "Правка контента требует идентичности (X-User-Id): "
                "анонимное устройство не меняет общий каталог.")
    if role not in WRITE_ROLES:
        return (FORBIDDEN,
                f"Роль {role!r} не правит контент — только teacher и admin.")
    if role == "admin":
        return None

    for subject_id in sorted({int(s) for s in subject_ids}):
        owner = repo.subject_owner(subject_id)
        if owner is not None and owner != actor:
            return (FORBIDDEN,
                    f"Предмет #{subject_id} принадлежит другому владельцу; "
                    f"выдача даёт право видеть, а не править.")
    return None


def check_entity_change(
    repo: Repository, kind: str, row: Optional[dict], data: dict,
    actor: Optional[str], role: str,
) -> Optional[tuple[int, str]]:
    """
    То же правило в форме, удобной синку: сущность задана видом, текущей
    строкой (если есть) и приезжающими данными.

    Для раздела в набор попадают оба предмета — прежний (из строки) и
    новый (из данных): это и есть тот самый перенос, ради которого
    `check_subject_write` принимает набор.
    """
    subject_ids: set[int] = set()
    if kind == "subject":
        if row is not None:
            subject_ids.add(int(row["id"]))
    else:
        if row is not None:
            subject_ids.add(int(row["subject_id"]))
        if data.get("subject_id") is not None:
            subject_ids.add(int(data["subject_id"]))
    return check_subject_write(repo, subject_ids, actor, role)
