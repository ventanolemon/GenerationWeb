import { HOLE } from "./fields";

/**
 * Палитра конструкций (план, §10.2).
 *
 * Каждая дырка обёрнута СВОЕЙ парой скобок — `{▯}`, а не просто `▯`.
 * Лишние скобки в LaTeX ничего не меняют (`{n}` и `n` рисуются
 * одинаково), но именно по ним поле опознаётся после того, как дырка
 * заполнена, и в него можно вернуться. Без этого «повторно
 * отредактировать» означало бы «стереть и набрать заново».
 *
 * `label` — это тоже LaTeX: кнопка показывает конструкцию так, как она
 * будет выглядеть, а не словом. Тот, кто не знает LaTeX (а палитра
 * ровно для него), ищет глазами дробь, а не слово «дробь».
 */
export interface Template {
  /** Что подставить. */
  latex: string;
  /** Что нарисовать на кнопке (KaTeX). */
  label: string;
  /** Подсказка при наведении и для программ чтения с экрана. */
  title: string;
}

