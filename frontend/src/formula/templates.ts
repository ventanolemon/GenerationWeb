/**
 * Добавить строку в систему или матрицу.
 *
 * Отдельной кнопкой, а не «умной» реакцией на Enter: система из трёх
 * уравнений встречается достаточно часто, чтобы не заставлять дописывать
 * `\\` руками, но угадывать намерение по Enter внутри формулы — верный
 * способ сломать ввод тому, кто хотел просто перевести строку.
 */
