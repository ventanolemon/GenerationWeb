"""
Константы и пути проекта. Все пути — относительно корня проекта,
без хардкода вроде C:\\Users\\... .

Поставка и данные — РАЗНЫЕ каталоги
-----------------------------------
`resources/` — это ПОСТАВКА: словари, звук, транскрипции и **шаблон** базы.
Всё оттуда читается и никогда не пишется.

Рабочая база лежит отдельно (`GEN_DATA_DIR`, по умолчанию `data/` рядом с
проектом) и создаётся при первом запуске копированием шаблона.

Почему так, а не как было
-------------------------
Раньше `DB_PATH` указывал прямо в `resources/`, и приложение писало в файл
поставки: заводило таблицы, переводило журнал в WAL, применяло миграции.
Из этого выросли два разных последствия, и оба уже случились.

**Первое — испорченный коммит.** Правка поставочной базы уезжала строкой
«Bin 139264 -> 147456 bytes», в которой не видно ничего. Так вышло
четырежды за одну работу, и ни разу намеренно.

**Второе — `database disk image is malformed` у пользователя.** Это была
ведущая версия дефекта, и она подтверждалась наблюдением: файл, который
приложение правит на месте, при неудачном стечении обстоятельств
(обновление поверх, копирование на полпути, права только на чтение)
оказывается битым. Теперь править нечего — рабочая копия своя.

Отдельная выгода, ради которой это понадобилось сейчас: в развёртывании
образ контейнера доступен только на чтение, а данные живут на томе. Пока
база лежала внутри поставки, это было невозможно.

Что происходит с уже накопленными данными
------------------------------------------
Ничего не теряется, и переноса руками не требуется. Прежняя рабочая база
лежала ровно там, где теперь лежит ШАБЛОН, — значит первый запуск после
обновления скопирует её в новое место со всем содержимым: учётными
записями, предметами, выдачами, попытками.

Старый файл при этом остаётся на месте и больше не используется.
Удалять его автоматически нельзя: это чужие данные, и решение об их
судьбе принимает человек, а не обновление.
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

ROOT_DIR = Path(__file__).resolve().parent

# ---------------------------------------------------------------- поставка

RESOURCES_DIR = ROOT_DIR / "resources"
WORDS_DIR = RESOURCES_DIR / "words"
UI_FILES_DIR = RESOURCES_DIR / "ui_files"

#: Шаблон базы: то, с чего начинается пустая установка. Только чтение.
DB_TEMPLATE = RESOURCES_DIR / "users_database.db"

# ------------------------------------------------------------------ данные

#: Каталог изменяемых данных. Переопределяется окружением — в контейнере
#: это том, на рабочей машине разработчика `data/` рядом с проектом.
DATA_DIR = Path(os.environ.get("GEN_DATA_DIR") or (ROOT_DIR / "data"))

#: Рабочая база. Отдельная переменная на случай, когда путь задают целиком
#: (например, один файл на несколько служб).
DB_PATH = Path(os.environ.get("GEN_DB_PATH") or (DATA_DIR / "users_database.db"))


def ensure_data_dir() -> Path:
    """
    Создать каталог данных и положить туда базу, если её ещё нет.

    Идемпотентно: существующую базу НЕ трогает никогда. Это главное
    свойство — иначе обновление приложения затирало бы накопленное.

    Копируется шаблон поставки; если шаблона нет (обрезанная сборка),
    создаётся пустой файл, и схему поднимут миграции. Пустая база — это
    рабочая установка без демо-данных, а не поломка.
    """
    DB_PATH.parent.mkdir(parents=True, exist_ok=True)
    if DB_PATH.exists():
        return DB_PATH
    if DB_TEMPLATE.exists():
        shutil.copyfile(DB_TEMPLATE, DB_PATH)
    else:
        DB_PATH.touch()
    return DB_PATH
